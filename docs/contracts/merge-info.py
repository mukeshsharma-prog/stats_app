#!/usr/bin/env python3
"""Put both contracts' `info` back into a `redocly join` output.

`redocly join` keeps the first input's `info` verbatim and discards the rest. Each of
our two contracts carries its principles in `info.description` — the ingest file's
response matrix and "what ZC configures", the read API's tenant-from-token and
keyset-pagination rules — and losing either from the rendered page would hand ZC a
document that states half the contract.

This script replaces the joined `info` with an umbrella title plus each source's
description under its own heading, and lifts the shared `contact`/`license` from the
first source. It also re-adds `x-tagGroups` naming the two halves, so Redoc's sidebar
shows them as two sections rather than one flat list. Nothing else in the joined
document is touched — paths, components and their order are `redocly join`'s.

Used only by build-html.sh; not a CI gate on its own.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import yaml

UMBRELLA_TITLE = "Zenner Datahub Core — Stats App: API contracts v1"
UMBRELLA_VERSION = "1.0.0-draft"
UMBRELLA_SUMMARY = (
    "The two HTTP contracts of the Stats App: the ingest endpoint Heimdal Core "
    "delivers to, and the read-only, tenant-scoped API consumers query."
)
UMBRELLA_PREAMBLE = """\
**Two contracts, one document, both draft pending ZC confirmation.**

| Half | Caller | Operations | Authentication | Source |
|---|---|---|---|---|
| **Ingest** | Heimdal Core (ZC) | `POST /stats` | OAuth2 client credentials implemented; mechanism awaiting ZC | `docs/contracts/openapi-input.yaml` |
| **Read API** | Tenant users and integrations | `GET /v1/stats/{type}`, `GET /v1/stats/{type}/{uid}` | Keycloak bearer token, tenant from the claim | `docs/contracts/openapi.yaml` |

They are separate sources on purpose — different caller, different authentication,
no shared version segment — and share their schemas by reference, so the envelope is
described exactly once. This page is generated by `docs/contracts/build-html.sh`;
edit the YAML, never this file.

---
"""


def _load(path: Path) -> dict:
    with path.open(encoding="utf-8") as handle:
        return yaml.safe_load(handle)


def _section(spec: dict, heading: str) -> str:
    info = spec.get("info", {})
    description = (info.get("description") or "").rstrip()
    return f"# {heading}\n\n{description}\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("joined", type=Path, help="output of `redocly join`")
    parser.add_argument("sources", type=Path, nargs="+", help="the joined inputs, in join order")
    parser.add_argument("-o", "--output", type=Path, required=True)
    args = parser.parse_args()

    joined = _load(args.joined)
    sources = [_load(path) for path in args.sources]

    sections = [
        _section(spec, f"Part {index}: {spec['info']['title']}")
        for index, spec in enumerate(sources, start=1)
    ]
    first_info = sources[0].get("info", {})

    joined["info"] = {
        "title": UMBRELLA_TITLE,
        "version": UMBRELLA_VERSION,
        "summary": UMBRELLA_SUMMARY,
        "description": UMBRELLA_PREAMBLE + "\n" + "\n---\n\n".join(sections),
        **{key: first_info[key] for key in ("contact", "license") if key in first_info},
    }

    joined["x-tagGroups"] = [
        {
            "name": spec["info"]["title"],
            "tags": [tag["name"] for tag in spec.get("tags", [])],
        }
        for spec in sources
    ]

    with args.output.open("w", encoding="utf-8") as handle:
        yaml.safe_dump(joined, handle, sort_keys=False, allow_unicode=True, width=100)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
