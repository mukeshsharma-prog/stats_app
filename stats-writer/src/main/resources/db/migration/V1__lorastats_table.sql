CREATE TABLE lorastats (
    uid                text        NOT NULL,
    tenant             text        NOT NULL,
    maintenant         text        NOT NULL,
    clsbox             text        NOT NULL,
    ts_server          timestamptz NOT NULL,
    ts_device          timestamptz NOT NULL,
    received_at        timestamptz NOT NULL DEFAULT now(),
    record_version     smallint,
    schema_version     smallint    NOT NULL,
    passthrough        jsonb,
    rx_nr_pkts         bigint      NOT NULL,
    rx_crc_missing     bigint      NOT NULL,
    rx_crc_bad         bigint      NOT NULL,
    rx_short_pkt       bigint,
    tx_success         bigint      NOT NULL,
    tx_failed          bigint      NOT NULL,
    tx_peek            bigint      NOT NULL,
    tx_peek_index_zero bigint      NOT NULL,
    tx_override        bigint      NOT NULL,
    tx_busy            bigint      NOT NULL,
    tx_dequeue_error   bigint      NOT NULL,
    tx_type_beacon     bigint      NOT NULL,
    chip_comm_error    bigint      NOT NULL,
    util_fopen_failed  bigint      NOT NULL,
    fsk_received       bigint,
    rx_type_arol       bigint,
    timespan           bigint,
    PRIMARY KEY (ts_device, uid)
) PARTITION BY RANGE (ts_device);
